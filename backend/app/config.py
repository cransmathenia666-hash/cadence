"""集中配置：会跨模块引用的端口、地址、开关都放这里，不散落在业务代码里。

为什么单开一个模块：`tasks/plan.md` 的风险表把「端口集中配置，不散落在代码里」
写成了约定——前端端口一旦散落在 CORS、文档、脚本三处，改一次就要满仓搜。
"""

# 前端开发服务端口（Next.js 默认 3000）。
FRONTEND_PORT = 3000

# 跨源（CORS）放行名单：开发期只放行本机前端。
#
# 为什么写两个：浏览器把 `localhost` 和 `127.0.0.1` 当成**两个不同的来源**，
# 只写一个的话，换个地址打开页面就会被 CORS 拦掉，而报错信息不会告诉你
# 「另一个写法没放行」——这是会查很久的那类问题。
#
# 边界：这是「只放行本机开发前端」，不是放开跨源。上线前按 SPEC 第 13 条加 token、
# 并把来源换成真实域名，名单里不该留本机地址太久。
FRONTEND_ORIGINS = (
    f"http://localhost:{FRONTEND_PORT}",
    f"http://127.0.0.1:{FRONTEND_PORT}",
)
